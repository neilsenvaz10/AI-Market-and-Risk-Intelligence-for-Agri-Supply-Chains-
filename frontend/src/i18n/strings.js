/**
 * Translate a key.
 * - Tries the requested language first.
 * - Falls back to English.
 * - Falls back to the key itself (never returns undefined).
 * - Supports {variable} interpolation.
 */
export function t(lang, key, vars = {}) {
  const template =
    STRINGS[lang]?.[key] ??
    STRINGS.en[key] ??
    key; // final safety net — never undefined

  if (process.env.NODE_ENV === 'development' && template === key) {
    console.warn(`[i18n] Missing translation: lang="${lang}" key="${key}"`);
  }

  return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}
